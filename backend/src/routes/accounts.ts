import { Router } from 'express';
import * as controller from '../controllers/account-controller.js';
import { requireAuth } from '../middleware/auth.js';
import { authRateLimit } from '../middleware/rate-limit.js';

export const accountsRouter = Router();
accountsRouter.post('/auth/signup', authRateLimit, controller.signup);
accountsRouter.post('/auth/signin', authRateLimit, controller.signin);
accountsRouter.post('/auth/refresh', authRateLimit, controller.refresh);
accountsRouter.post('/auth/recover', authRateLimit, controller.recover);
accountsRouter.post('/auth/verify', authRateLimit, controller.verify);
accountsRouter.post('/auth/password', requireAuth, authRateLimit, controller.updatePassword);
accountsRouter.post('/auth/logout', requireAuth, controller.logout);
accountsRouter.get('/auth/me', requireAuth, controller.me);
accountsRouter.get('/users/me', requireAuth, controller.me);
accountsRouter.patch('/users/me', requireAuth, controller.updateProfile);
accountsRouter.get('/users/me/addresses', requireAuth, controller.addresses);
accountsRouter.post('/users/me/addresses', requireAuth, controller.saveAddress);
accountsRouter.put('/users/me/addresses/:id', requireAuth, controller.saveAddress);
accountsRouter.delete('/users/me/addresses/:id', requireAuth, controller.deleteAddress);
accountsRouter.post('/users/me/addresses/:id/default', requireAuth, controller.defaultAddress);
accountsRouter.get('/users/me/preferences', requireAuth, controller.preferences);
accountsRouter.patch('/users/me/preferences', requireAuth, controller.updatePreferences);
accountsRouter.get('/users/me/notification-preferences', requireAuth, controller.notificationPreferences);
accountsRouter.patch('/users/me/notification-preferences', requireAuth, controller.updateNotificationPreferences);
accountsRouter.get('/users/me/blocked-users', requireAuth, controller.blocks);
accountsRouter.post('/users/me/blocked-users', requireAuth, controller.block);
accountsRouter.delete('/users/me/blocked-users/:id', requireAuth, controller.unblock);
accountsRouter.get('/notifications', requireAuth, controller.notifications);
accountsRouter.get('/notifications/unread-count', requireAuth, controller.unreadNotifications);
accountsRouter.post('/notifications/read-all', requireAuth, controller.readAllNotifications);
accountsRouter.delete('/notifications', requireAuth, controller.clearNotifications);
accountsRouter.post('/notifications/:id/read', requireAuth, controller.readNotification);
accountsRouter.delete('/notifications/:id', requireAuth, controller.deleteNotification);
