import { Router } from 'express';
import { requireAuth,requireAdminRole } from '../middleware/auth.js';
import * as controller from '../controllers/admin-users-controller.js';
import { activityStream } from '../realtime/activity-stream.js';
import * as orders from '../controllers/admin-orders-controller.js';
export const adminUsersRouter=Router();
adminUsersRouter.get('/admin/orders',requireAuth,requireAdminRole('operations','admin','super_admin'),orders.list);
adminUsersRouter.get('/admin/orders/:id',requireAuth,requireAdminRole('operations','admin','super_admin'),orders.detail);
adminUsersRouter.use('/admin/users',requireAuth,requireAdminRole('super_admin'));
adminUsersRouter.get('/admin/users',controller.users);
adminUsersRouter.post('/admin/users',controller.add);
adminUsersRouter.get('/admin/users/:id',controller.detail);
adminUsersRouter.patch('/admin/users/:id',controller.edit);
adminUsersRouter.delete('/admin/users/:id',controller.deactivate);
adminUsersRouter.get('/admin/platform/activity',requireAuth,requireAdminRole('super_admin'),controller.activity);
adminUsersRouter.get('/admin/platform/audit',requireAuth,requireAdminRole('super_admin'),controller.audit);
adminUsersRouter.get('/admin/platform/analytics',requireAuth,requireAdminRole('super_admin'),controller.analytics);
adminUsersRouter.get('/admin/platform/stream',requireAuth,requireAdminRole('super_admin'),activityStream);
adminUsersRouter.get('/admin/platform/metrics',requireAuth,requireAdminRole('super_admin'),controller.monitoring);
adminUsersRouter.get('/admin/platform/activity/:id/record',requireAuth,requireAdminRole('super_admin'),controller.relatedRecord);
